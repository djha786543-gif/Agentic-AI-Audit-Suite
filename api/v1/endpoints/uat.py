def _summary_from_report(path: Path, report: Dict[str, Any]) -> Dict[str, Any]:
    summary = report.get("summary", {})
    top_failures: Dict[str, int] = {}
    for step in report.get("steps", []):
        if not step.get("success", False):
            key = f"{step.get('method', 'UNK')} {step.get('path', 'UNKNOWN')} -> {step.get('status_code', 0)}"
            top_failures[key] = top_failures.get(key, 0) + 1

    top_failures_sorted = sorted(
        [{"endpoint": k, "count": v} for k, v in top_failures.items()],
        key=lambda x: x["count"],
        reverse=True,
    )[:10]

    return {
        "file": path.name,
        "path": str(path),
        "last_modified": datetime.fromtimestamp(path.stat().st_mtime).isoformat(),
        "run_id": report.get("run_id"),
        "started_at": report.get("started_at"),
        "finished_at": report.get("finished_at"),
        "summary": {
            "total_steps": summary.get("total_steps", len(report.get("steps", []))),
            "failed_steps": summary.get("failed_steps", 0),
            "success_rate_pct": summary.get("success_rate_pct", 0),
            "p95_latency_ms": summary.get("p95_latency_ms"),
            "improvement_candidates": summary.get("improvement_candidates", len(report.get("improvement_candidates", []))),
        },
        "top_failures": top_failures_sorted,
    }



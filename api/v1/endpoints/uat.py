    proc: Optional[subprocess.Popen] = _RUNNER_STATE.get("process")
    if proc is None or proc.poll() is not None:
        return {"stopped": False, "status": _runner_status(), "message": "No active run"}

    proc.terminate()
    try:
        proc.wait(timeout=8)
    except Exception:
        proc.kill()

    _RUNNER_STATE["finished_at"] = datetime.utcnow().isoformat()
    _RUNNER_STATE["exit_code"] = proc.poll()
    return {"stopped": True, "status": _runner_status()}



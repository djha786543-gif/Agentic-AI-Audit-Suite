def _reports_dir() -> Path:
    # /repo/api/v1/endpoints/uat.py -> /repo
    repo_root = Path(__file__).resolve().parents[3]
    return repo_root / "uat_reports"


def _load_json(path: Path) -> Dict[str, Any]:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def _save_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _save_json(path: Path, payload: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")


def _latest_report_path() -> Path:
    reports_dir = _reports_dir()
    files = sorted(
        reports_dir.glob(REPORT_GLOB),
        key=lambda p: p.stat().st_mtime,
        reverse=True,
    )
    if not files:
        raise HTTPException(status_code=404, detail="No UAT reports available")
    return files[0]


def _phase2_patch_dir() -> Path:
    return _reports_dir() / PATCH_DIR_NAME


def _pick_python_executable(repo_root: Path) -> str:
    venv_win = repo_root / ".venv" / "Scripts" / "python.exe"
    venv_unix = repo_root / ".venv" / "bin" / "python"
    if venv_win.exists():
        return str(venv_win)
    if venv_unix.exists():
        return str(venv_unix)
    return sys.executable


def _runner_status() -> Dict[str, Any]:
    proc: Optional[subprocess.Popen] = _RUNNER_STATE.get("process")
    running = False
    exit_code = _RUNNER_STATE.get("exit_code")

    if proc is not None:
        poll = proc.poll()
        if poll is None:
            running = True
        else:
            exit_code = poll
            _RUNNER_STATE["exit_code"] = poll
            _RUNNER_STATE["finished_at"] = _RUNNER_STATE.get("finished_at") or datetime.utcnow().isoformat()

    latest_report = None
    try:
        latest_report = _latest_report_path().name
    except Exception:
        latest_report = None

    return {
        "running": running,
        "started_at": _RUNNER_STATE.get("started_at"),
        "finished_at": _RUNNER_STATE.get("finished_at"),
        "exit_code": exit_code,
        "command": _RUNNER_STATE.get("command"),
        "log_path": _RUNNER_STATE.get("log_path"),
        "last_error": _RUNNER_STATE.get("last_error"),
        "latest_report": latest_report,
    }


def _report_failure_profile(report: Dict[str, Any]) -> Dict[str, Any]:
    steps = report.get("steps", [])
    total = len(steps)
    failed = [s for s in steps if not s.get("success", False)]
    failed_count = len(failed)
    failure_pct = (failed_count / total * 100.0) if total else 0.0

    disconnected = 0
    server_errors = 0
    for step in failed:
        code = int(step.get("status_code", 0) or 0)
        err_text = str(step.get("error", ""))
        if code == 0 and "RemoteDisconnected" in err_text:
            disconnected += 1
        if 500 <= code <= 599:
            server_errors += 1

    return {
        "total_steps": total,
        "failed_steps": failed_count,
        "failure_pct": round(failure_pct, 2),
        "server_error_count": server_errors,
        "disconnect_count": disconnected,
    }


def _status_count(report: Dict[str, Any], code: int) -> int:
    count = 0
    for step in report.get("steps", []):
        if int(step.get("status_code", 0) or 0) == code:
            count += 1
    return count


def _evaluate_readiness(report: Dict[str, Any]) -> Dict[str, Any]:
    profile = _report_failure_profile(report)
    summary = report.get("summary", {})
    total = int(profile["total_steps"] or 0)
    failure_pct = float(profile["failure_pct"])
    disconnect_count = int(profile["disconnect_count"])
    server_error_count = int(profile["server_error_count"])
    server_error_pct = round((server_error_count / total) * 100.0, 2) if total else 100.0
    disconnect_pct = round((disconnect_count / total) * 100.0, 2) if total else 100.0
    p95_latency_ms = float(summary.get("p95_latency_ms") or 0)

    industry_ready = (
        failure_pct <= 2.0
        and disconnect_count == 0
        and server_error_pct <= 1.0
        and p95_latency_ms <= 1000.0
    )
    pilot_ready = (
        failure_pct <= 8.0
        and disconnect_pct <= 1.0
        and server_error_pct <= 3.0
        and p95_latency_ms <= 1500.0
    )

    level = "not_ready"
    if industry_ready:
        level = "industry_ready"
    elif pilot_ready:
        level = "pilot_ready"

    return {
        "level": level,
        "metrics": {
            "total_steps": total,
            "failed_steps": int(profile["failed_steps"]),
            "failure_pct": failure_pct,
            "disconnect_count": disconnect_count,
            "disconnect_pct": disconnect_pct,
            "server_error_count": server_error_count,
            "server_error_pct": server_error_pct,
            "p95_latency_ms": p95_latency_ms,
            "status_500": _status_count(report, 500),
            "status_502": _status_count(report, 502),
            "status_503": _status_count(report, 503),
            "status_504": _status_count(report, 504),
            "status_0": _status_count(report, 0),
        },
        "thresholds": {
            "industry_ready": {
                "failure_pct_lte": 2.0,
                "disconnect_count_eq": 0,
                "server_error_pct_lte": 1.0,
                "p95_latency_ms_lte": 1000.0,
            },
            "pilot_ready": {
                "failure_pct_lte": 8.0,
                "disconnect_pct_lte": 1.0,
                "server_error_pct_lte": 3.0,
                "p95_latency_ms_lte": 1500.0,
            },
        },
    }



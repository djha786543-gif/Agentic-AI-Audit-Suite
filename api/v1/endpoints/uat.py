@router.get("/compare/latest")
def compare_latest() -> Dict[str, Any]:
    reports_dir = _reports_dir()
    if not reports_dir.exists():
        raise HTTPException(status_code=404, detail="No uat_reports directory found")

    files = sorted(
        reports_dir.glob(REPORT_GLOB),
        key=lambda p: p.stat().st_mtime,
    )
    if len(files) < 2:
        raise HTTPException(status_code=404, detail="Need at least 2 reports to compare")

    old_path = files[-2]
    new_path = files[-1]
    old = _load_json(old_path)
    new = _load_json(new_path)

    old_sum = old.get("summary", {})
    new_sum = new.get("summary", {})

    def fail_map(report: Dict[str, Any]) -> Dict[str, int]:
        m: Dict[str, int] = {}
        for step in report.get("steps", []):
            if not step.get("success", False):
                key = f"{step.get('method', 'UNK')} {step.get('path', 'UNKNOWN')}"
                m[key] = m.get(key, 0) + 1
        return m

    old_fail = fail_map(old)
    new_fail = fail_map(new)

    deltas: Dict[str, int] = {}
    for key in set(old_fail.keys()) | set(new_fail.keys()):
        deltas[key] = new_fail.get(key, 0) - old_fail.get(key, 0)

    improvements = sorted(
        [{"endpoint": k, "delta": v} for k, v in deltas.items() if v < 0],
        key=lambda x: x["delta"],
    )
    regressions = sorted(
        [{"endpoint": k, "delta": v} for k, v in deltas.items() if v > 0],
        key=lambda x: x["delta"],
        reverse=True,
    )

    return {
        "old_file": old_path.name,
        "new_file": new_path.name,
        "summary": {
            "old_total_steps": old_sum.get("total_steps", len(old.get("steps", []))),
            "new_total_steps": new_sum.get("total_steps", len(new.get("steps", []))),
            "old_failed_steps": old_sum.get("failed_steps", 0),
            "new_failed_steps": new_sum.get("failed_steps", 0),
            "old_success_rate_pct": old_sum.get("success_rate_pct", 0),
            "new_success_rate_pct": new_sum.get("success_rate_pct", 0),
            "old_p95_latency_ms": old_sum.get("p95_latency_ms"),
            "new_p95_latency_ms": new_sum.get("p95_latency_ms"),
        },
        "improvements": improvements[:15],
        "regressions": regressions[:15],
    }



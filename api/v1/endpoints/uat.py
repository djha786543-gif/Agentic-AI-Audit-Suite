    reports_dir = _reports_dir()
    if not reports_dir.exists():
        return {"reports_dir": str(reports_dir), "reports": [], "count": 0}

    files = sorted(
        reports_dir.glob(REPORT_GLOB),
        key=lambda p: p.stat().st_mtime,
        reverse=True,
    )[: max(1, min(limit, 100))]

    reports: List[Dict[str, Any]] = []
    for p in files:
        try:
            report = _load_json(p)
            reports.append(_summary_from_report(p, report))
        except Exception as exc:
            reports.append(
                {
                    "file": p.name,
                    "path": str(p),
                    "last_modified": datetime.fromtimestamp(p.stat().st_mtime).isoformat(),
                    "error": f"Could not parse report: {exc}",
                }
            )

    return {"reports_dir": str(reports_dir), "count": len(reports), "reports": reports}


